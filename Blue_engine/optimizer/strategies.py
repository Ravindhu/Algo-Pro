"""
optimizer/strategies.py - what actually gets called once per trial.

THE CONTRACT (this is the whole interface)
-----------------------------------------
A strategy is any callable (or ``module:function`` string) matching:

    fn(params: Dict[str, Any], ctx: Dict[str, Any]) -> Dict[str, Any]
    returns {"returns": [float, ...],            # per-period strategy returns
             "ok": True}                          # or ok=False + "reason"
    ctx carries {"seed": int, "periods": int, "cost_bps": float, ...}

That is deliberately tiny. It means:

* a real backtest harness plugs in (``e2e_replay`` / ``backtest_ocl_confirm``
  style),
* a portfolio walk-forward plugs in (``portfolio/optim/benchmark.run_walk_forward``),
* a synthetic function plugs in for tests,

...and ``objective.py`` never needs to know which of those it is talking to.
This mirrors the design of ``ml/evaluation/walk_forward.py``, which takes a
generic ``fit_fn``/``predict_fn`` pair rather than importing sklearn.

WHY THE SYNTHETIC BENCHMARK SHIPS IN PRODUCTION CODE
----------------------------------------------------
``synthetic_band_strategy`` has a **known optimum** (``spaces.SYNTHETIC_OPTIMUM``).
Without it, the only way to test an optimiser is to check that it "ran without
exception" - which is exactly the test that passes while the optimiser silently
returns garbage. With it, a test can assert the search *converged to the known
peak*. That is the difference between testing the code and testing the answer.

It is deterministic given a seed and needs no data, no broker and no network,
so it also serves as the documented way to demo the engine on a fresh machine.

HONESTY NOTE ON THE SYNTHETIC STRATEGY
--------------------------------------
Its returns are generated by a fixed formula, not by any market. Anything it
produces is **SIMULATED**. It is a test fixture. It must never appear in a
report as a performance claim, and the engine labels its studies
``"data_class": "simulated"`` so the dashboard cannot present them as live.
"""
from __future__ import annotations

import importlib
import inspect
import math
import random
from typing import Any, Callable, Dict, List, Optional, Tuple

from . import logger

__all__ = ["StrategyFn", "resolve_strategy", "synthetic_band_strategy",
           "synthetic_prices", "available_builtin_strategies",
           "accepts_bars", "call_strategy"]

StrategyFn = Callable[[Dict[str, Any], Dict[str, Any]], Dict[str, Any]]


# --------------------------------------------------------------------------- #
# Bars-aware adapter (Phase 3 of OPTIMIZER_HEADER_PLAN.md)
# --------------------------------------------------------------------------- #


def accepts_bars(fn: Any) -> bool:
    """True when ``fn`` accepts a third ``bars`` argument.

    The default strategy contract is ``fn(params, ctx) -> dict``. New
    strategies that want real bars can opt into the wider contract
    ``fn(params, ctx, bars=None) -> dict``. This helper inspects the
    signature and returns True for callables that declare a third
    parameter (positional or keyword). Cached callables and builtins
    that don't expose a signature return False, so they keep working
    unchanged.

    The check is intentionally lenient: any third parameter named
    ``bars`` OR any third positional parameter at all is accepted.
    Strict name-checking would be a foot-gun for the common case of
    ``def f(p, c, bars=None)`` versus ``def f(p, c, df=None)``.
    """
    if not callable(fn):
        return False
    try:
        sig = inspect.signature(fn)
    except (TypeError, ValueError):                       # builtins, C funcs
        return False
    params = list(sig.parameters.values())
    if len(params) < 3:
        return False
    # Reject *args-only callables: ``def f(*args)`` technically has
    # unbounded positional arity but the engine never passes more than
    # two positional args today, so the safe default is "no".
    third = params[2]
    if third.kind is inspect.Parameter.VAR_POSITIONAL:
        return False
    return True


def call_strategy(fn: Any, params: Dict[str, Any],
                   ctx: Dict[str, Any], bars: Optional[List[Dict[str, Any]]] = None
                   ) -> Dict[str, Any]:
    """Call a strategy with the widest contract it accepts.

    Strategies that declare a third ``bars`` parameter get the bars;
    strategies that don't are called with the original two-argument
    contract. This is the single chokepoint that lets the engine
    consume cached real data without forcing every existing strategy
    to update its signature.
    """
    if accepts_bars(fn) and bars is not None:
        return fn(params, ctx, bars)
    return fn(params, ctx)


# --------------------------------------------------------------------------- #
# Resolution
# --------------------------------------------------------------------------- #

#: Built-ins addressable by name from the CLI, so no import path is needed for
#: the common cases.
_BUILTIN: Dict[str, str] = {
    "synthetic": "blue_engine.optimizer.strategies.synthetic_band_strategy",
}


def available_builtin_strategies() -> Dict[str, str]:
    """Name -> dotted path for the built-in strategy functions."""
    return dict(_BUILTIN)


def resolve_strategy(spec: Any) -> Tuple[Optional[StrategyFn], Optional[str]]:
    """Turn a spec into a callable. Returns ``(fn, error)`` - never raises.

    Accepted specs:
        * a callable                -> used directly,
        * ``"builtin_name"``        -> looked up in the built-in table,
        * ``"module:function"``     -> imported (dotted module allowed),
        * ``"module.function"``     -> imported if the module resolves.

    Returning an error string rather than raising matters for the CLI: a typo in
    a strategy path should print one clear line and exit, not dump a traceback
    that buries the actual message.
    """
    if callable(spec):
        return spec, None

    if not isinstance(spec, str) or not spec.strip():
        return None, "strategy spec must be a callable or a name/path string"

    name = spec.strip()

    if name in _BUILTIN:
        name = _BUILTIN[name]

    if ":" in name:
        mod_name, _, fn_name = name.partition(":")
    else:
        # Split on the LAST dot: package.subpkg.module.function
        mod_name, _, fn_name = name.rpartition(".")
    if not mod_name or not fn_name:
        # A bare name with no separators is a missing built-in, not a dotted path.
        return None, (f"unknown strategy {spec!r}; built-ins are "
                      f"{sorted(_BUILTIN)} or use 'module:function'")

    try:
        module = importlib.import_module(mod_name)
    except Exception as exc:  # noqa: BLE001 - report, do not crash the CLI
        return None, f"could not import {mod_name!r}: {type(exc).__name__}: {exc}"

    fn = getattr(module, fn_name, None)
    if fn is None:
        return None, f"{mod_name!r} has no attribute {fn_name!r}"
    if not callable(fn):
        return None, f"{mod_name}.{fn_name} is not callable"
    return fn, None


# --------------------------------------------------------------------------- #
# Synthetic market data (deterministic, no network)
# --------------------------------------------------------------------------- #


def synthetic_prices(periods: int = 600, *, seed: int = 7,
                     start: float = 100.0) -> list:
    """A deterministic pseudo-price series for tests and demos.

    Deliberately NOT a random walk with drift: a drift would make almost any
    strategy look profitable, which would let a broken objective pass. This
    series mean-reverts around ``start`` with a mild trend cycle, so a strategy
    has to time it to earn anything - i.e. there is something to optimise, and
    a strategy that does nothing scores approximately zero.

    **SIMULATED data.** Not a market. See the module docstring.
    """
    rng = random.Random(int(seed))
    px = float(start)
    out = [px]
    for i in range(1, int(periods)):
        # A slow cycle (period ~120 bars) plus noise. The cycle is what gives
        # the "trend" mode something real to capture.
        cycle = math.sin(2.0 * math.pi * i / 120.0) * 0.004
        noise = rng.gauss(0.0, 0.008)
        px *= (1.0 + cycle + noise)
        # Keep the series finite and positive: a negative price would make
        # return arithmetic meaningless and silently poison every metric.
        px = max(px, 1.0)
        out.append(px)
    return out


def _sma(values: list, n: int) -> list:
    """Simple moving average, ``None`` until the window is full.

    ``None`` rather than a partial average on purpose: a partial window at the
    start of the series is a different estimator, and using it silently is a
    mild look-ahead/instability source in the first ``n`` bars of every trial.
    """
    n = max(1, int(n))
    out = [None] * len(values)
    running = 0.0
    for i, v in enumerate(values):
        running += v
        if i >= n:
            running -= values[i - n]
        if i >= n - 1:
            out[i] = running / n
    return out


def synthetic_band_strategy(params: Dict[str, Any],
                            ctx: Dict[str, Any]) -> Dict[str, Any]:
    """A crossover strategy on synthetic data, with a KNOWN optimum.

    The truth this function encodes is in ``spaces.SYNTHETIC_OPTIMUM`` - that
    constant is the single source of truth, and it is **measured, not asserted**.
    As re-measured under audit finding C1c it is::

        mode      == "trend"     (the synthetic series has a real cycle)
        fast      == 4
        slow      == 18
        threshold == 0.0
        vol_target == 0.40

    with ``hold_bars`` IRRELEVANT: the fixture's signals are contiguous (every
    bar from ``slow`` onward emits a non-zero signal, gap = 1), so the hold
    counter is refreshed before it can expire and every value of ``hold_bars``
    gives a bit-identical result. Do not assert on it.

    ``mode`` is the decisive parameter: ``meanrev`` scores about -4.6 against
    +3.8 for ``trend``, because inverting a cycle-tracking signal loses money on
    this series. That categorical is what makes a convergence test meaningful.

    Returns per-period strategy returns, net of ``ctx["cost_bps"]`` on each
    change of position. Costs are charged on *transitions only* - charging a
    round trip every bar would make the optimum trivially "never trade", which
    would test the cost model rather than the search.

    **SIMULATED.** This is a fixture, not a strategy. See module docstring.
    """
    periods = int(ctx.get("periods", 600) or 600)
    seed = int(ctx.get("seed", 7) or 7)
    cost_bps = float(ctx.get("cost_bps", 10.0) or 0.0)

    fast = int(params.get("fast", 8) or 8)
    slow = int(params.get("slow", 21) or 21)
    threshold = float(params.get("threshold", 0.004) or 0.0)
    hold_bars = int(params.get("hold_bars", 10) or 10)
    vol_target = float(params.get("vol_target", 0.12) or 0.12)
    mode = str(params.get("mode", "trend") or "trend").lower()

    # Defence in depth: the space's constraints already reject fast >= slow, but
    # a strategy callable may be invoked directly (tests, other callers), so it
    # must not divide by a zero-length window.
    if fast >= slow or fast < 1:
        return {"ok": False, "reason": f"invalid MA pair fast={fast} slow={slow}",
                "returns": []}
    if periods < slow + hold_bars + 10:
        return {"ok": False, "reason": "not enough synthetic periods",
                "returns": []}

    prices = synthetic_prices(periods, seed=seed)
    f = _sma(prices, fast)
    s = _sma(prices, slow)

    # --- desired position each bar ---------------------------------------- #
    signal = [0.0] * periods
    for i in range(periods):
        if f[i] is None or s[i] is None or s[i] == 0:
            continue
        spread = (f[i] - s[i]) / s[i]          # normalised MA gap
        raw = spread if mode == "trend" else -spread
        if abs(raw) < threshold:
            raw = 0.0
        signal[i] = 1.0 if raw > 0 else (-1.0 if raw < 0 else 0.0)

    # --- hold_bars: the desired position persists for N bars --------------- #
    held: list = [0.0] * periods
    remaining = 0
    current = 0.0
    for i in range(periods):
        if signal[i] != 0.0:
            current = signal[i]
            remaining = hold_bars
        if remaining > 0:
            held[i] = current
            remaining -= 1
        else:
            held[i] = 0.0
            current = 0.0
            remaining = 0

    # --- realised returns, vol-targeted, net of cost ---------------------- #
    rets: list = []
    # Volatility scaling: size the position to a target annualised vol. A flat
    # size would make the "vol_target" parameter irrelevant and it would then be
    # ranked as noise by the importance plot - a false finding.
    day_vol = 0.008 * math.sqrt(252.0)          # matches the noise in synthetic_prices
    scale = (vol_target / day_vol) if day_vol > 0 else 1.0
    scale = min(max(scale, 0.1), 3.0)           # never leverage the fixture

    prev = 0.0
    for i in range(1, periods):
        r = (prices[i] - prices[i - 1]) / prices[i - 1]
        pos = held[i - 1]                       # act on the previous bar's signal
        gross = pos * r * scale
        # Cost only when the position actually changes.
        turn = abs(pos - prev)
        cost = turn * (cost_bps / 10000.0)
        rets.append(gross - cost)
        prev = pos

    return {"ok": True, "returns": rets,
            "data_class": "simulated",
            "note": "synthetic fixture - not market data"}
